public class sum_of_2_nos {

    public static void sum(int a, int b){
        System.out.println("Sum is: " + (a+b));
    }
    public static void sum(double a, double b){
        System.out.println("Sum is: "+ (a+b));
    }
    public static void main(String args []){
        sum(5,6);
        sum(6.8,9.1);
    }
}
